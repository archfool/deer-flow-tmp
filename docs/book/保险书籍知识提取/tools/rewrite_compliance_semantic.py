T = [x[0] for x in P]


def render(i, title, core, name, body, concepts, anti, example, links):
    antis = [x.rstrip("。") for x in anti.split("；")]
    first = core.split("。")[0]
    refs=[]
    for ref in links.split(","):
        n=int(ref[2:]); refs.append(f"- **{ref} {T[n-1]}**：提供相邻的规范或合同检验。")
    return f"""# Chapter {i}: {title}

## Core Idea

{core}

## Frameworks Introduced

### {name}

{body}

**何时使用**：销售说明、保单检视或争议初筛时；先核验规范时效，再应用框架。

## Key Concepts

- **概念关系**：{concepts}通过“{name}”进入同一条件分析，任何单个术语都不能直接决定结论。
- **来源边界**：区分书中历史材料、当前规范、合同文本、客户事实和专业意见，并标注日期。

## Mental Models

- **条件树而非口号**：{first}。
- **合同与法律双定位**：先找合同责任，再找当前规范对其成立、效力或解释的影响。
- **销售留痕也是证据**：询问、告知、说明、客户确认和版本均需真实可追溯。

## Anti-patterns

{chr(10).join('- ' + x + '。' for x in antis)}

## Worked Example

{example}

## Key Takeaways

1. {first}。
2. 使用“{name}”完成条件分析：{body}
3. 先排除“{antis[0]}”，再形成带来源日期的结论。

## Connects To

{chr(10).join(refs)}
"""


def main():
    files=sorted(ROOT.glob("ch*.md"))
    if len(files)!=len(P): raise SystemExit(f"expected {len(P)}, found {len(files)}")
    for i,(path,p) in enumerate(zip(files,P),1): path.write_text(render(i,*p),encoding="utf-8")


if __name__ == "__main__": main()
