def main():
    files = sorted(ROOT.glob("ch*.md"))
    if len(files) != len(P):
        raise SystemExit(f"expected {len(P)}, found {len(files)}")
    for i, (path, profile) in enumerate(zip(files, P), 1):
        path.write_text(render(i, *profile), encoding="utf-8")


if __name__ == "__main__":
    main()
